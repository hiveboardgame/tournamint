/// Which internal bound a tournament outgrew, reported by
/// [`PairingError::LimitExceeded`].
///
/// The engine works in fixed-width integers so that score comparisons stay
/// exact; each variant names the quantity that no longer fits.
#[derive(Clone, Copy, Debug, Eq, PartialEq, thiserror::Error)]
pub enum PairingLimit {
    /// A player's score plus their acceleration bonus.
    #[error("accelerated score")]
    AcceleratedScore,
    /// A player's Burstein adjusted score: their real score plus draw
    /// substitutions for earlier members of a trailing zero-bye sequence.
    #[error("adjusted score")]
    AdjustedScore,
    /// The sum of a player's Burstein opponent-score contributions.
    #[error("Buchholz total")]
    BuchholzTotal,
    /// One Burstein Sonneborn-Berger term: primary points earned in a round
    /// multiplied by that round's Burstein opponent-score contribution. A
    /// played round uses the opponent's adjusted score; an unplayed virtual
    /// round uses the player's own current real score.
    #[error("Sonneborn-Berger product")]
    SonnebornBergerProduct,
    /// The sum of a player's Burstein Sonneborn-Berger contributions.
    #[error("Sonneborn-Berger total")]
    SonnebornBergerTotal,
}

/// A semantic reason automatic selection could not produce a round.
#[derive(Clone, Copy, Debug, Eq, PartialEq, thiserror::Error)]
pub enum PairingError {
    /// No pairing of this field satisfies the system's rules — for instance
    /// every remaining player has already met every other.
    #[error("no valid pairing")]
    NoValidPairing,
    /// The field is odd, but no player is eligible for the bye.
    #[error("no eligible bye player")]
    NoBye,
    /// A named pairing-score quantity exceeded its exact supported bound.
    #[error("limit exceeded: {0}")]
    LimitExceeded(PairingLimit),
}

/// An invariant failure in automatic selection, not exhaustion of legal pairings.
#[derive(Clone, Copy, Debug, Eq, PartialEq, thiserror::Error)]
pub enum PairingInternalError {
    /// Generated pairings did not assign every eligible player exactly once.
    #[error("generated round does not assign every eligible player exactly once")]
    InvalidGeneratedRound,
    /// Generated byes violate requested-bye or pairing-allocated-bye rules.
    #[error("generated byes violate requests, field parity, or bye eligibility")]
    InvalidGeneratedByes,
    /// Unmatched players remained after the last score group was processed.
    #[error("unmatched players remain with no score group left to process")]
    EmptyScoreGroup,
}

/// A private failure from the automatic pairing pipeline.
#[derive(Clone, Copy, Debug, Eq, PartialEq, thiserror::Error)]
pub(crate) enum PairingFailure {
    #[error("{0}")]
    Pairing(#[from] PairingError),
    #[error("internal pairing failure: {0}")]
    Internal(#[from] PairingInternalError),
}

#[cfg(test)]
impl PairingFailure {
    pub(crate) fn pairing_error(self) -> PairingError {
        match self {
            Self::Pairing(error) => error,
            Self::Internal(error) => panic!("unexpected internal pairing failure: {error}"),
        }
    }
}
